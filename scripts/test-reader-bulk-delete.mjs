import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { chunkBulkMessageIds, toggleVisibleSelection } from "../src/client/mailBulk.ts";

const fixture = Array.from({ length: 100 }, (_, index) => `mail-${index + 1}`);
const selected = toggleVisibleSelection([], fixture);
assert.equal(selected.length, 100, "Select All should include every visible message, not just the first 50");
assert.deepEqual(toggleVisibleSelection(selected, fixture), [], "Select All toggles off when all visible messages were selected");
assert.deepEqual(toggleVisibleSelection(["other"], fixture.slice(0, 3)), ["other", ...fixture.slice(0, 3)]);
assert.deepEqual(toggleVisibleSelection(["other", ...fixture.slice(0, 3)], fixture.slice(0, 3)), ["other"]);
const batches = chunkBulkMessageIds(selected);
assert.deepEqual(batches.map(b => b.length), [50, 50], "Split bulk calls to meet the API maximum");
assert.deepEqual(batches.flat(), selected);
assert.deepEqual(chunkBulkMessageIds([...fixture, fixture[0]]).map(b => b.length), [50, 50]);
assert.deepEqual(chunkBulkMessageIds([]), []);

const app = readFileSync(new URL("../src/client/App.tsx", import.meta.url), "utf8");
const reader = readFileSync(new URL("../src/client/components/MessageReader.tsx", import.meta.url), "utf8");
const css = readFileSync(new URL("../src/client/ui-overrides.css", import.meta.url), "utf8");
const dialog = readFileSync(new URL("../src/client/components/DeleteConfirmationDialog.tsx", import.meta.url), "utf8");
assert.match(app, /toggleVisibleSelection\(current, ids\)/);
// Every selected ID is batched (≤50 per call), per owning account in All inboxes.
assert.match(app, /groupByAccount\(requestedIds, ownerOf\)\]\s*\.flatMap\(\(\[accountId, ids\]\) => chunkBulkMessageIds\(ids\)/);
assert.match(app, /body: JSON.stringify\(\{ ids: batch, action \}\)/);
assert.ok(app.includes("setSelectedMailIds([]);"), "Clear selected IDs after deletion");
assert.equal(app.includes("setSelectedMailIds(failed.map"), false);
assert.doesNotMatch(app, /current.length < 50/);
assert.doesNotMatch(app, /!confirm\("Permanently delete/);
assert.match(app, /<DeleteConfirmationDialog/);
assert.match(dialog, /role="dialog"/);
assert.match(dialog, /aria-modal="true"/);
assert.match(dialog, /Cancel/);
assert.match(dialog, /Delete permanently/);
assert.match(dialog, /onConfirm/);
assert.match(reader, /className="unsubscribe-action"/);
assert.match(css, /\.app-shell\.message-open \.reader-pane:not\(\.reader-empty\)/);
assert.match(css, /bottom: calc\(65px \+ env\(safe-area-inset-bottom\)\)/);
assert.match(css, /height: auto;/);
assert.match(css, /\.app-shell\.message-open \.reader-scroll/);
assert.match(css, /flex: 1 1 0;/);
assert.match(css, /\.app-shell\.message-open \.reader-reply-bar/);
console.log("PASS: Visible mobile action footer, all-row selection, 50-message batching and irreversible deletion confirmation");
